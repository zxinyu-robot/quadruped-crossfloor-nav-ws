#!/usr/bin/env python3
"""由 contracts/runtime_contract.json 生成双实现共享的契约常量。

生成物（均需入库，构建期不依赖本脚本）：
  include/legged_nav/contract_gen.hpp   C++20 权威实现使用
  src/legged_nav/contract_gen.py        Python 演示层使用

用法：
  python3 scripts/gen_contract.py            # 生成/覆盖
  python3 scripts/gen_contract.py --check    # 只校验是否已同步（CI 门禁）
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts" / "runtime_contract.json"
CPP_OUT = ROOT / "include" / "legged_nav" / "contract_gen.hpp"
PY_OUT = ROOT / "src" / "legged_nav" / "contract_gen.py"

HEADER = "AUTO-GENERATED by scripts/gen_contract.py from contracts/runtime_contract.json."
WARN = "请勿手改；修改契约后重新运行 python3 scripts/gen_contract.py。"


def _load() -> dict:
    with CONTRACT.open(encoding="utf-8") as fh:
        data = json.load(fh)
    ti = data["task_intent"]
    # 契约自检：技能表与白名单必须一致，避免生成出自相矛盾的常量
    if list(ti["skills"]) != list(ti["allowed_skills"]):
        raise SystemExit("contract error: skills 与 allowed_skills 顺序/成员不一致")
    for name, spec in ti["skills"].items():
        if "kind" not in spec or "timeout_s" not in spec:
            raise SystemExit(f"contract error: skills.{name} 缺少 kind/timeout_s")
    return data


def _cpp_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _cpp_double(value: float) -> str:
    text = repr(float(value))
    return text if "." in text or "e" in text else text + ".0"


def render_cpp(data: dict) -> str:
    ti = data["task_intent"]
    norm = ti["normalization"]
    lines = [
        "// clang-format off",
        "#pragma once",
        "/// @file contract_gen.hpp",
        f"/// @brief 运行时契约常量（{HEADER}）。",
        f"/// {WARN}",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace legged_nav::contract {",
        "",
        f"inline constexpr int kVersion = {data['version']};",
        f"inline constexpr std::string_view kIntentSchema = {_cpp_str(ti['schema'])};",
        f"inline constexpr std::string_view kFeedbackSchema = "
        f"{_cpp_str(ti['feedback_schema'])};",
        f"inline constexpr bool kTrimStrings = {'true' if norm['trim_strings'] else 'false'};",
        f"inline constexpr bool kCoerceNonString = "
        f"{'true' if norm['coerce_non_string'] else 'false'};",
        "",
    ]

    def emit_array(name: str, values: list[str]) -> None:
        lines.append(f"inline constexpr std::string_view {name}[] = {{")
        lines.extend(f"    {_cpp_str(v)}," for v in values)
        lines.append("};")
        lines.append("")

    emit_array("kAllowedPlatforms", ti["allowed_platforms"])
    emit_array("kAllowedSkills", ti["allowed_skills"])
    emit_array("kForbiddenControlKeys", ti["forbidden_control_keys"])

    lines.append("struct SkillSpec {")
    lines.append("    std::string_view name;")
    lines.append("    std::string_view kind;")
    lines.append("    double timeout_s;")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr SkillSpec kSkills[] = {")
    for name, spec in ti["skills"].items():
        lines.append(f"    {{{_cpp_str(name)}, {_cpp_str(spec['kind'])}, "
                     f"{_cpp_double(spec['timeout_s'])}}},")
    lines.append("};")
    lines.append("")

    lines.append("struct SkillParam {")
    lines.append("    std::string_view skill;")
    lines.append("    std::string_view key;")
    lines.append("    std::string_view value;")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr SkillParam kSkillParams[] = {")
    for name, spec in ti["skills"].items():
        for key, value in spec.get("params", {}).items():
            lines.append(f"    {{{_cpp_str(name)}, {_cpp_str(key)}, {_cpp_str(value)}}},")
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace legged_nav::contract")
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def render_py(data: dict) -> str:
    ti = data["task_intent"]
    norm = ti["normalization"]
    lines = [
        '"""运行时契约常量（自动生成，请勿手改）。',
        "",
        "来源：contracts/runtime_contract.json · 生成器：scripts/gen_contract.py",
        "与 C++ 头文件 include/legged_nav/contract_gen.hpp 同源。",
        '"""',
        "from __future__ import annotations",
        "",
        f"VERSION = {data['version']}",
        f'INTENT_SCHEMA = "{ti["schema"]}"',
        f'FEEDBACK_SCHEMA = "{ti["feedback_schema"]}"',
        f"TRIM_STRINGS = {norm['trim_strings']}",
        f"COERCE_NON_STRING = {norm['coerce_non_string']}",
        "",
    ]

    def emit_set(name: str, values: list[str]) -> None:
        lines.append(f"{name} = frozenset({{")
        lines.extend(f'    "{v}",' for v in values)
        lines.append("})")
        lines.append("")

    emit_set("ALLOWED_PLATFORMS", ti["allowed_platforms"])
    emit_set("ALLOWED_SKILLS", ti["allowed_skills"])
    emit_set("FORBIDDEN_CONTROL_KEYS", ti["forbidden_control_keys"])

    lines.append("SKILL_KINDS = {")
    lines.extend(f'    "{name}": "{spec["kind"]}",' for name, spec in ti["skills"].items())
    lines.append("}")
    lines.append("")
    lines.append("SKILL_TIMEOUTS_S = {")
    lines.extend(f'    "{name}": {_cpp_double(spec["timeout_s"])},'
                 for name, spec in ti["skills"].items())
    lines.append("}")
    lines.append("")
    lines.append("SKILL_PARAMS = {")
    for name, spec in ti["skills"].items():
        params = spec.get("params", {})
        if not params:
            continue
        rendered = ", ".join(f'"{k}": "{v}"' for k, v in params.items())
        lines.append(f'    "{name}": {{{rendered}}},')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="仅校验生成物是否同步")
    args = ap.parse_args()

    data = _load()
    targets = {CPP_OUT: render_cpp(data), PY_OUT: render_py(data)}

    if args.check:
        drift = [p for p, text in targets.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        if drift:
            for path in drift:
                print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
            print("运行 python3 scripts/gen_contract.py 重新生成后提交", file=sys.stderr)
            return 1
        print("contract generated files are in sync")
        return 0

    for path, text in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
